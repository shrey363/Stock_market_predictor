def category_priority(category: str) -> int:
    """Return the priority index of ``category`` (lower fires first)."""
    try:
        return EVENT_CATEGORIES.index(category)
    except ValueError as exc:  # pragma: no cover - guarded by callers
        raise KeyError(f"unknown event category {category!r}") from exc


