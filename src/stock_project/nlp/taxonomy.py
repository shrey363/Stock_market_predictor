#: Categories in **priority order**: when a headline matches several, the first wins.
#:
#: Rationale (a judgment call the manual review is meant to test): specific,
#: high-consequence instruments outrank general diplomacy, and a policy instrument
#: (sanctions, tariffs) outranks a supply mention, because the policy is the subject
#: of the sentence. Ties are documented rather than hidden.
