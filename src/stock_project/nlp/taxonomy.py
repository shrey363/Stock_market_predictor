"""Event taxonomy and the transparent lexicons the Phase 2 baselines use.

Everything here is data, not logic: editing a list is how the baseline is tuned, so
every prediction can be traced to a human-readable term (see
``docs/annotation_guidelines.md`` for the definitions, tie-break rules, and known
failure modes).

Two separate concerns live here on purpose:

* **Event categories** describe *what kind of event* the text is about.
* **Sentiment terms** describe the *tone* of the text.

Sentiment is not severity, and neither is a prediction about market impact.
"""

